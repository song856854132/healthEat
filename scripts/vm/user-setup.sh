#!/usr/bin/env bash
# healthEat shared dev VM: per-person setup. Run as yourself (no sudo) after bootstrap.sh:
#   bash scripts/vm/user-setup.sh
# Installs Claude Code (your own Max login) and gstack, signs you into GitHub and gcloud,
# clones the repo, installs dependencies and the Playwright browser, and writes
# ~/.env.staging from Secret Manager. Re-runnable.
set -euo pipefail

REPO="${HEALTHEAT_REPO:-song856854132/healthEat}"
PROJECT="${HEALTHEAT_GCP_PROJECT:-study-488509}"
WORK="$HOME/healthEat"

mkdir -p "$HOME/.local/bin" "$HOME/.npm-global/bin"
export PATH="$HOME/.local/bin:$HOME/.npm-global/bin:$HOME/.bun/bin:$PATH"
export NPM_CONFIG_PREFIX="$HOME/.npm-global"

step() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

step "bun (gstack's setup needs it)"
if ! command -v bun >/dev/null 2>&1; then
  curl -fsSL https://bun.sh/install | bash >/dev/null
  export PATH="$HOME/.bun/bin:$PATH"
fi
bun --version

step "Claude Code"
if ! command -v claude >/dev/null 2>&1; then
  curl -fsSL https://claude.ai/install.sh | bash
fi
claude --version

step "gstack (per repo CLAUDE.md)"
if [ ! -d "$HOME/.claude/skills/gstack" ]; then
  git clone --depth 1 https://github.com/garrytan/gstack.git "$HOME/.claude/skills/gstack"
  (cd "$HOME/.claude/skills/gstack" && ./setup --team) || echo "gstack setup reported an error; rerun ./setup later"
fi

step "GitHub"
if ! gh auth status >/dev/null 2>&1; then
  echo "Sign in to GitHub (choose HTTPS, then the browser/device code flow):"
  gh auth login --hostname github.com --git-protocol https --web
fi
gh auth setup-git
if [ -z "$(git config --global user.name || true)" ]; then
  name="$(gh api user -q .name 2>/dev/null || true)"
  [ -n "$name" ] || name="$(gh api user -q .login 2>/dev/null || echo "$USER")"
  git config --global user.name "$name"
fi
if [ -z "$(git config --global user.email || true)" ]; then
  echo "git user.email is not set. Enter the email you want on commits:"; read -r email; git config --global user.email "$email"
fi

step "gcloud (your own identity, for Secret Manager)"
if ! gcloud auth list --filter=status:ACTIVE --format='value(account)' 2>/dev/null | grep -q .; then
  gcloud auth login --no-launch-browser
fi
gcloud config set project "$PROJECT" >/dev/null

step "repo"
if [ ! -d "$WORK/.git" ]; then
  gh repo clone "$REPO" "$WORK"
fi
cd "$WORK"
git pull --ff-only || true
npm ci
npm run build:shared
npx playwright install chromium || echo "Playwright browser install failed; e2e runs in CI anyway"

step "staging secrets -> ~/.env.staging (git-ignored, mode 600)"
tmp="$(mktemp)"
{
  echo "# generated by scripts/vm/user-setup.sh on $(date -u +%FT%TZ); do not commit"
  for pair in "SESSION_SECRET:session-secret-staging" "MONGODB_URI:mongodb-uri-staging" "USDA_API_KEY:usda-api-key" "ANTHROPIC_API_KEY:anthropic-api-key"; do
    var="${pair%%:*}"; secret="${pair##*:}"
    if val="$(gcloud secrets versions access latest --secret="$secret" --project="$PROJECT" 2>/dev/null)"; then
      printf '%s=%s\n' "$var" "$val"
    else
      echo "# $var: no access to secret $secret (ask the owner for roles/secretmanager.secretAccessor)"
    fi
  done
  echo "MONGODB_DB=healtheat_dev_$(printf '%s' "$USER" | tr -c 'a-zA-Z0-9_\n' '_')"
  echo "API_ORIGIN=http://localhost:4000"
  echo "PORT=4000"
} > "$tmp"
install -m 600 "$tmp" "$HOME/.env.staging"; rm -f "$tmp"
grep -c '^[A-Z_]*=' "$HOME/.env.staging" | xargs -I{} echo "{} variables written"

step "Claude Code login"
if ! claude auth status >/dev/null 2>&1; then
  cat <<'MSG'
Run `claude` once now. It prints a login URL: open it in the browser on your own computer,
sign in with your Claude (Max) account, and paste the code back here when prompted.
MSG
fi

step "done"
cat <<MSG
Work from: $WORK   (use git worktrees per task, e.g. git worktree add ../healthEat-t21 -b t21-...)
Load staging env in a shell:  set -a; . ~/.env.staging; set +a
Run locally:  npm run dev:api   and   npm run dev:web   (in two tmux panes)
Docs: docs/ONBOARDING.md, docs/team-workflow.md, docs/designs/healtheat-nutrient-coach.md
MSG
